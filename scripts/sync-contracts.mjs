import fs from 'node:fs/promises';
for (const [name, destination] of [['tool-schemas.json','gateway-v2-contracts.json'], ['host-instructions.md','gateway-v2-instructions.md']]) {
const source=new URL(`../contracts/${name}`,import.meta.url);
const target=new URL(`../../mcp/src/${destination}`,import.meta.url);
const data=await fs.readFile(source,'utf8');
if(process.argv.includes('--check')) {
 if(await fs.readFile(target,'utf8')!==data) throw new Error('MCP v2 schemas drifted; run sync-contracts.mjs');
} else {await fs.writeFile(target,data);}
}

for (const [sourceName, destination] of [['tool-schemas.json','webmcp/gateway-v2-contracts.json'], ['host-instructions.md','webmcp/gateway-v2-instructions.md'], ['ask-limits.json','domain/gateway-v2-limits.json']]) {
 const data=await fs.readFile(new URL(`../contracts/${sourceName}`,import.meta.url),'utf8');
 const target=new URL(`../../app/src/lib/${destination}`,import.meta.url);
 if(process.argv.includes('--check')) {if(await fs.readFile(target,'utf8')!==data) throw new Error(`App v2 contract drift: ${destination}`);}
 else await fs.writeFile(target,data);
}

// The agent skill (app/supabase/functions/_shared/skill-package.ts) teaches the
// same contract over HTTP. Edge Functions cannot import Markdown, so the two
// files are embedded in one generated Deno module: the skill served by
// agent-gateway and the MCP tools then read the same text.
{
 const schemas=await fs.readFile(new URL('../contracts/tool-schemas.json',import.meta.url),'utf8');
 const instructions=await fs.readFile(new URL('../contracts/host-instructions.md',import.meta.url),'utf8');
 const data=[
  '// GENERATED by gateway/scripts/sync-contracts.mjs from gateway/contracts/. Do not edit.',
  '// The Gateway v2 agent contract: the MCP tool schemas and host instructions.',
  `export const GATEWAY_V2_TOOL_SCHEMAS = ${JSON.stringify(JSON.parse(schemas),null,2)} as const`,
  `export const GATEWAY_V2_HOST_INSTRUCTIONS: string = ${JSON.stringify(instructions)}`,
  '',
 ].join('\n');
 const target=new URL('../../app/supabase/functions/_shared/gateway-v2-contract.ts',import.meta.url);
 if(process.argv.includes('--check')) {if(await fs.readFile(target,'utf8').catch(()=>'')!==data) throw new Error('Agent skill contract drift: _shared/gateway-v2-contract.ts');}
 else await fs.writeFile(target,data);
}
