#!/usr/bin/env python3
"""Generate administrative schema views; never connect to or mutate a database."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MANAGED = {"public", "auth", "storage", "realtime", "extensions", "vault", "cron", "net", "graphql", "graphql_public", "supabase_migrations", "gateway_v2", "kvk_cache", "information_schema"}


def ident(value):
    if not isinstance(value, str) or not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", value):
        raise ValueError(f"Invalid SQL identifier: {value!r}")
    return '"' + value + '"'


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def generate(manifest):
    if manifest.get("mode") != "administrative_views":
        raise ValueError("Only administrative views are supported")
    sql = [
        "-- Generated by scripts/generate-domain-schemas.py from supabase/domain-schemas.json.",
        "-- This is an additive administrative directory, not a physical table move.",
        "-- Public API, RPC, upsert and Realtime references continue using canonical objects.",
        "-- Apply atomically using the normal migration runner.",
        "SET LOCAL lock_timeout = '3s';",
        "SET LOCAL statement_timeout = '60s';",
    ]
    domains, sources = set(), set()
    for domain in manifest["domains"]:
        name = domain["name"]
        if name in MANAGED or name.startswith("pg_") or name in domains:
            raise ValueError(f"Reserved or duplicate domain: {name}")
        domains.add(name)
        schema = ident(name)
        sql.extend([
            "", f"CREATE SCHEMA {schema} AUTHORIZATION postgres;",
            f"COMMENT ON SCHEMA {schema} IS {literal(domain['description'] + '. Administrative views; canonical tables remain in their original schemas.')} ;",
            f"REVOKE ALL ON SCHEMA {schema} FROM PUBLIC, anon, authenticated;",
            f"GRANT USAGE ON SCHEMA {schema} TO service_role;",
        ])
        names = set()
        for relation in domain["relations"]:
            source = (relation["source_schema"], relation["source_name"])
            if source[0] not in {"public", "gateway_v2"} or source in sources:
                raise ValueError(f"Unexpected or duplicate source: {source}")
            sources.add(source)
            if relation["name"] in names:
                raise ValueError(f"Duplicate alias in {name}")
            names.add(relation["name"])
            alias = schema + "." + ident(relation["name"])
            canonical = ident(source[0]) + "." + ident(source[1])
            sql.extend([
                f"CREATE VIEW {alias} WITH (security_invoker = true) AS SELECT * FROM {canonical};",
                f"COMMENT ON VIEW {alias} IS {literal('Apiosk administrative alias of ' + '.'.join(source) + '. No copied data; runtime writes and Realtime use the canonical object.')} ;",
                f"REVOKE ALL ON {alias} FROM PUBLIC, anon, authenticated, service_role;",
                f"GRANT SELECT ON {alias} TO service_role;",
            ])
    return "\n".join(sql) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("migration", type=Path, help="File created with supabase migration new")
    parser.add_argument("--check", action="store_true", help="Only compare the generated SQL")
    args = parser.parse_args()
    output = generate(json.loads((ROOT / "supabase/domain-schemas.json").read_text()))
    if args.check:
        if args.migration.read_text() != output:
            raise SystemExit("Migration differs from the domain manifest")
        print("Migration matches domain manifest")
    else:
        if not args.migration.exists():
            raise SystemExit("Create the migration with supabase migration new first")
        args.migration.write_text(output)
        print(args.migration)
